CREATE TABLE LabResults (
  LabResultID UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
  LabOrderID UNIQUEIDENTIFIER NOT NULL,
  ResultText NVARCHAR(MAX) NULL,
  AttachmentPath NVARCHAR(500) NULL,
  ReviewedByUserID UNIQUEIDENTIFIER NULL,
  ReviewedAt DATETIME2 NULL,
  RecordedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT UQ_LabResults_LabOrderID UNIQUE (LabOrderID),
  CONSTRAINT FK_LabResults_LabOrder FOREIGN KEY (LabOrderID) REFERENCES LabOrders(LabOrderID),
  CONSTRAINT FK_LabResults_ReviewedBy FOREIGN KEY (ReviewedByUserID) REFERENCES Users(UserID)
);
